#include<stdio.h>

int main(void) {
    int age = 22;
    float height = 5.8f;
    char grade = 'A';
    double percentage = 98.75;

    printf("Age: %d\n", age);
    printf("Height: %.2f\n", height);
    printf("Grade: %c\n", grade);
    printf("Percentage: %.2lf\n", percentage);

    return 0;
    

}